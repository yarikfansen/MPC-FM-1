#!/bin/sh
# Writes app/build_id.h (not in git): the build number INFO shows, = commits
# on this branch + the short hash. Run before building a package.
cd "$(dirname "$0")/.." || exit 1
n=$(git rev-list --count HEAD 2>/dev/null || echo 0)
h=$(git rev-parse --short HEAD 2>/dev/null || echo dev)
printf '/* Generated by tools/stamp_build.sh */\n#define FM1_BUILD_ID "%s ` %s"\n' "$n" "$h" > app/build_id.h
# FM1_RC=ALPHA sh tools/stamp_build.sh: INFO shows "V1 ALPHA" instead of "V1 BETA"
[ -n "$FM1_RC" ] && printf '#define FM1_VERSION_TAG "%s"
' "$FM1_RC" >> app/build_id.h
